//! `lvpm.lock`: the complete resolved set of a project.
//!
//! `lvpm.toml` says what a project asks for; the lock says what that came to:
//! every package, direct or transitive, with its exact version, the SHA-256 of
//! its archive and the source it came from. It is lvpm's file, rewritten whole,
//! and its text is a function of its content alone: packages are sorted by
//! name, nothing carries a timestamp or a path, so the same inputs always give
//! the same bytes.
//!
//! ```toml
//! # (generated header)
//! version = 1                          # the format of this file
//! labview = "2024"                     # the LabVIEW it was resolved for
//!
//! [inputs]                             # the manifest it was resolved from
//! defaults = false
//! sources = ["http://host/feed"]
//!
//! [inputs.dependencies]
//! beta = ">=1.0"
//!
//! [[package]]
//! name = "alpha"
//! version = "2.0"
//! sha256 = "..."
//! md5 = "..."                          # only when the feed lists one
//! source = "local"                     # or the feed's index URL
//! requires = ["beta"]                  # the locked packages it needs
//! dev = true                           # only when nothing but dev dependencies need it
//!
//! [[unresolved]]                       # a requirement no source lists
//! name = "ni_lib_missing"
//! required_by = "beta"
//! ```

use crate::project::{Constraint, Project};
use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::Path;

/// The lock's file name; it sits beside `lvpm.toml`.
pub const FILE_NAME: &str = "lvpm.lock";
/// The format this lvpm writes. A lock with an older number is stale.
pub const FORMAT_VERSION: u32 = 1;
/// The `source` of a package that came from a local folder or the cache.
pub const LOCAL_SOURCE: &str = "local";

const HEADER: &str = "\
# This file is generated by `lvpm lock`. Do not edit it.
# It records the exact packages lvpm.toml resolved to; commit it with the project.

";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lockfile {
    /// The lock-format version.
    pub version: u32,
    /// The manifest's `labview` the lock was resolved for.
    pub labview: String,
    pub inputs: Inputs,
    #[serde(default, rename = "package", skip_serializing_if = "Vec::is_empty")]
    pub packages: Vec<LockedPackage>,
    /// Requirements of the locked packages that no source lists.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub unresolved: Vec<LockedUnresolved>,
}

/// What the manifest said when the lock was made, so that a later change to it
/// can be noticed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Inputs {
    /// Whether the public indexes were consulted too.
    pub defaults: bool,
    /// The hosted `[sources]` index folders, as the manifest lists them.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub sources: Vec<String>,
    /// `[dependencies]`: name and constraint as written.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub dependencies: BTreeMap<String, String>,
    /// `[dev-dependencies]`: name and constraint as written.
    #[serde(
        default,
        rename = "dev-dependencies",
        skip_serializing_if = "BTreeMap::is_empty"
    )]
    pub dev_dependencies: BTreeMap<String, String>,
}

impl Inputs {
    /// The inputs a manifest gives.
    pub fn of(project: &Project) -> Inputs {
        let constraints = |entries: &[(String, Constraint)]| {
            entries
                .iter()
                .map(|(name, constraint)| (name.clone(), constraint_text(constraint)))
                .collect()
        };
        Inputs {
            defaults: project.default_sources,
            sources: project.sources.iter().map(|(_, url)| url.clone()).collect(),
            dependencies: constraints(&project.dependencies),
            dev_dependencies: constraints(&project.dev_dependencies),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    /// The SHA-256 of the archive, lowercase hex.
    pub sha256: String,
    /// The MD5 the feed lists for the archive, when it lists one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub md5: Option<String>,
    /// The feed's index URL, or [`LOCAL_SOURCE`].
    pub source: String,
    /// The locked packages this one requires, by name.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub requires: Vec<String>,
    /// Needed only through `[dev-dependencies]`.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub dev: bool,
}

/// A requirement that no source lists, and the package that has it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedUnresolved {
    pub name: String,
    pub required_by: String,
}

/// A constraint as the manifest writes it: `1.2`, `>=1.2` or `*`.
pub fn constraint_text(constraint: &Constraint) -> String {
    match constraint {
        Constraint::Exact(version) => version.raw.clone(),
        Constraint::AtLeast(version) => format!(">={}", version.raw),
        Constraint::Any => "*".to_string(),
    }
}

fn name_key(name: &str) -> String {
    name.to_lowercase()
}

impl Lockfile {
    /// The same lock with everything in its one canonical order, which is the
    /// order the file is written in.
    fn sorted(&self) -> Lockfile {
        let mut lock = self.clone();
        lock.packages
            .sort_by_cached_key(|package| (name_key(&package.name), package.version.clone()));
        for package in &mut lock.packages {
            package.requires.sort_by_cached_key(|name| name_key(name));
            package.requires.dedup();
        }
        lock.unresolved.sort_by_cached_key(|unresolved| {
            (
                name_key(&unresolved.name),
                name_key(&unresolved.required_by),
            )
        });
        lock
    }

    /// The file's text: a header, then the lock in its canonical order.
    pub fn to_toml(&self) -> Result<String> {
        let body = toml::to_string(&self.sorted()).context("writing lvpm.lock")?;
        Ok(format!("{HEADER}{body}"))
    }

    pub fn parse(text: &str) -> Result<Lockfile> {
        toml::from_str(text).context("parsing lvpm.lock")
    }

    pub fn read(path: &Path) -> Result<Lockfile> {
        let text =
            std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
        Lockfile::parse(&text).with_context(|| format!("in {}", path.display()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::version::Version;

    fn package(name: &str, version: &str) -> LockedPackage {
        LockedPackage {
            name: name.to_string(),
            version: version.to_string(),
            sha256: "ab".repeat(32),
            md5: None,
            source: LOCAL_SOURCE.to_string(),
            requires: Vec::new(),
            dev: false,
        }
    }

    fn lock() -> Lockfile {
        let mut beta = package("beta", "1.0");
        beta.md5 = Some("cd".repeat(16));
        beta.source = "http://127.0.0.1:8090/feed/index.vipr".to_string();
        beta.requires = vec!["alpha".to_string()];
        let mut caraya = package("caraya", "1.0");
        caraya.dev = true;
        Lockfile {
            version: FORMAT_VERSION,
            labview: "2024".to_string(),
            inputs: Inputs {
                defaults: false,
                sources: vec!["http://127.0.0.1:8090/feed".to_string()],
                dependencies: BTreeMap::from([("beta".to_string(), ">=1.0".to_string())]),
                dev_dependencies: BTreeMap::from([("caraya".to_string(), "*".to_string())]),
            },
            packages: vec![package("alpha", "2.0"), beta, caraya],
            unresolved: vec![LockedUnresolved {
                name: "ni_lib_missing".to_string(),
                required_by: "beta".to_string(),
            }],
        }
    }

    #[test]
    fn a_lock_survives_being_written_and_read() {
        let written = lock().to_toml().unwrap();
        assert_eq!(Lockfile::parse(&written).unwrap(), lock());
    }

    #[test]
    fn the_file_says_it_is_generated_and_shows_only_what_is_set() {
        let text = lock().to_toml().unwrap();
        assert!(
            text.starts_with("# This file is generated by `lvpm lock`. Do not edit it."),
            "{text}"
        );
        // `dev` and `md5` are written where they apply and nowhere else.
        assert_eq!(text.matches("dev = true").count(), 1, "{text}");
        assert_eq!(text.matches("dev = false").count(), 0, "{text}");
        assert_eq!(text.matches("md5 = ").count(), 1, "{text}");
        assert_eq!(text.matches("[[package]]").count(), 3, "{text}");
    }

    #[test]
    fn the_same_lock_always_gives_the_same_bytes() {
        assert_eq!(lock().to_toml().unwrap(), lock().to_toml().unwrap());
    }

    #[test]
    fn the_order_the_lock_was_built_in_does_not_show_in_the_file() {
        let mut ordered = lock();
        ordered.packages[1].requires = vec!["alpha".to_string(), "Zed".to_string()];
        let mut shuffled = ordered.clone();
        shuffled.packages.reverse();
        for package in &mut shuffled.packages {
            package.requires.reverse();
        }
        assert_eq!(ordered.to_toml().unwrap(), shuffled.to_toml().unwrap());
    }

    #[test]
    fn packages_are_sorted_by_name_whatever_their_case() {
        let mut lock = lock();
        lock.packages = vec![package("Zeta", "1.0"), package("alpha", "1.0")];
        let text = lock.to_toml().unwrap();
        assert!(
            text.find("name = \"alpha\"").unwrap() < text.find("name = \"Zeta\"").unwrap(),
            "{text}"
        );
    }

    #[test]
    fn inputs_follow_the_manifest_in_the_manifests_spelling() {
        let project = crate::project::parse(
            "[project]\nlabview = \"2024\"\n\n[sources]\nmirror = \"http://h/feed\"\ndefaults = false\n\n\
             [dependencies]\nbeta = \">=1.0\"\nalpha = \"2.0\"\n\n[dev-dependencies]\ncaraya = \"*\"\n",
        )
        .unwrap();
        let inputs = Inputs::of(&project);
        assert!(!inputs.defaults);
        assert_eq!(inputs.sources, ["http://h/feed"]);
        assert_eq!(
            inputs.dependencies.into_iter().collect::<Vec<_>>(),
            [
                ("alpha".to_string(), "2.0".to_string()),
                ("beta".to_string(), ">=1.0".to_string())
            ]
        );
        assert_eq!(inputs.dev_dependencies["caraya"], "*");
    }

    #[test]
    fn a_constraint_is_written_as_the_manifest_reads_it() {
        for text in ["1.2.3", ">=1.2", "*"] {
            let constraint = Constraint::parse(text).unwrap();
            assert_eq!(constraint_text(&constraint), text);
        }
        assert_eq!(
            constraint_text(&Constraint::Exact(Version::parse("1.0-1"))),
            "1.0-1"
        );
    }

    #[test]
    fn text_that_is_not_a_lock_is_an_error_naming_the_file() {
        let why = Lockfile::parse("labview = 3").unwrap_err().to_string();
        assert!(why.contains("lvpm.lock"), "{why}");
    }

    #[test]
    fn reading_a_lock_from_disk_gives_what_was_written() {
        let dir = std::env::temp_dir().join(format!("lvpm-lockfile-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join(FILE_NAME);
        std::fs::write(&path, lock().to_toml().unwrap()).unwrap();
        assert_eq!(Lockfile::read(&path).unwrap(), lock());
        std::fs::remove_dir_all(&dir).ok();
    }
}
